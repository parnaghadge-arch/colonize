/**
 * Permission model
 * ----------------
 * Every protected capability is a `module:action` string. Modules mirror the product
 * surface (and the §73 sidebar), actions mirror the verbs a user can perform.
 *
 * The matrix below declares *default* grants per role. At runtime these defaults are
 * materialised into each society database (`roles` + `role_permissions` collections) so an
 * administrator can add or revoke individual permissions without a code change.
 */


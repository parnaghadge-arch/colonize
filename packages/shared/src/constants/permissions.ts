export type PermissionModule = (typeof PERMISSION_MODULES)[number];

export const PERMISSION_ACTIONS = [
  'view',
  'create',
  'update',
  'delete',
  'approve',
  'reject',
  'assign',
  'publish',
  'export',
  'generate',
  'refund',
  'cancel',
  'vote',
  'book',
  'acknowledge',
  'record',
  'scan',
  'manage',
] as const;

export type PermissionAction = (typeof PERMISSION_ACTIONS)[number];

export type Permission = `${PermissionModule}:${PermissionAction}`;

export const permission = (module: PermissionModule, action: PermissionAction): Permission =>
  `${module}:${action}` as Permission;

/** `module:*` grants every action on that module. */
export const all = (module: PermissionModule): Permission => `${module}:*` as Permission;

/** Expand a role's declared grants (which may contain `module:*`) into concrete permissions. */
export function expandPermissions(grants: readonly string[]): Set<string> {
  const out = new Set<string>();
  for (const g of grants) {
    const [mod, act] = g.split(':');
    if (!mod) continue;
    if (act === '*') {
      for (const a of PERMISSION_ACTIONS) out.add(`${mod}:${a}`);
    } else if (act) {
      out.add(g);
    }
  }
  return out;
}

